<section>
	<p>
		Эти условия описывают правила игры в Global Assault. Создавая аккаунт или входя в игру, вы соглашаетесь с ними.
		Если вы не согласны, не играйте.
	</p>
	<p>
		Обработка ваших данных описана в <a href="/global-assault/privacy">Политике конфиденциальности</a>, которая
		является частью этих условий.
	</p>
</section>

<section>
	<h2>1. Кто мы</h2>
	<p>
		Global Assault делает GOATFIST Interactive — независимая студия, которую ведёт частное лицо в Бразилии. Чтобы
		связаться с нами, пишите на <a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a>.
	</p>
</section>

<section>
	<h2>2. Минимальный возраст</h2>
	<p>
		Чтобы играть, вам должно быть 18 лет или больше. В игре есть бои с оружием и открытый чат с другими игроками,
		поэтому она не предназначена для несовершеннолетних.
	</p>
	<p>
		Если мы обнаружим, что аккаунт принадлежит человеку младше 18 лет, мы закроем его и удалим его данные.
	</p>
</section>

<section>
	<h2>3. Закрытая бета</h2>
	<p>
		Global Assault всё ещё в разработке. Во время беты в игре могут быть ошибки, она может быть недоступна из-за
		технического обслуживания или сильно меняться от версии к версии.
	</p>
	<p>
		Мы можем обнулить аккаунты, предметы и прогресс в конце беты или если этого потребует какая-то проблема. Когда
		это возможно, мы заранее предупреждаем об этом в Discord.
	</p>
</section>

<section>
	<h2>4. Ваш аккаунт</h2>
	<p>
		Вы можете играть как гость или создать аккаунт с логином и паролем. Аккаунт личный: не одалживайте и не
		продавайте его и не пользуйтесь чужим. Берегите свой пароль. За всё, что происходит в вашем аккаунте, отвечаете
		вы.
	</p>
	<p>
		Гостевой аккаунт привязан к устройству. Если вы удалите игру или смените телефон, этот аккаунт может быть
		потерян.
	</p>
</section>

<section>
	<h2>5. Правила поведения</h2>
	<p>Мы хотим честных матчей и такой атмосферы, в которой хочется играть всем. Поэтому запрещено:</p>
	<ul>
		<li>использовать читы, сторонние программы, макросы или что-либо ещё, что даёт преимущество извне игры;</li>
		<li>намеренно использовать ошибки вместо того, чтобы сообщать о них;</li>
		<li>оскорблять других игроков, угрожать им или преследовать их, в чате или через имя;</li>
		<li>публиковать язык вражды, сексуальный контент, мошенничество или чьи-либо персональные данные;</li>
		<li>выдавать себя за команду игры;</li>
		<li>покупать, продавать или обменивать аккаунты и предметы за деньги;</li>
		<li>атаковать, перегружать наши серверы или пытаться их взломать.</li>
	</ul>
</section>

<section>
	<h2>6. Наказания</h2>
	<p>
		Если кто-то нарушает правила, мы можем, в зависимости от серьёзности нарушения, вынести предупреждение,
		отключить чат, временно заблокировать аккаунт или заблокировать его навсегда. За читерство блокировка может
		последовать сразу.
	</p>
	<p>
		Если вы считаете, что произошла ошибка, напишите на <a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a>,
		указав имя аккаунта и что случилось. Мы разберёмся и ответим.
	</p>
</section>

<section>
	<h2>7. Игровые предметы и валюта</h2>
	<p>
		Валюта, оружие, предметы внешнего вида и другие предметы игры существуют только внутри неё. Они не имеют
		денежной ценности, не могут быть обменены на деньги и не являются вашей собственностью: вы получаете право
		пользоваться ими, пока ваш аккаунт активен.
	</p>
	<p>
		В бете нет покупок за реальные деньги. Если это изменится, условия будут обновлены заранее.
	</p>
</section>

<section>
	<h2>8. Игра и ваш контент</h2>
	<p>
		Игра, её код, графика и товарные знаки защищены правами интеллектуальной собственности. Вы получаете личную,
		бесплатную и непередаваемую лицензию на игру. Запрещено копировать, изменять, перепродавать или распространять
		игру, а также создавать её параллельные серверы или версии.
	</p>
	<p>
		То, что вы пишете в чате, и выбранное вами имя остаются вашими, но вы разрешаете нам показывать их в игре и
		удалять их, если они нарушают эти правила.
	</p>
</section>

<section>
	<h2>9. Доступность и ответственность</h2>
	<p>
		Мы делаем всё возможное, чтобы игра хорошо работала, но не гарантируем, что она всегда будет доступна, будет
		работать без ошибок или на всех устройствах. Мы можем в любой момент изменить, приостановить или прекратить
		работу игры или её частей.
	</p>
	<p>
		В пределах, допускаемых законом, мы не отвечаем за косвенные потери, например за прогресс или предметы,
		утраченные из-за технических сбоев. Ничто в этих условиях не лишает вас прав, которые гарантирует вам Кодекс
		защиты прав потребителей Бразилии (Código de Defesa do Consumidor).
	</p>
</section>

<section>
	<h2>10. Как закрыть аккаунт</h2>
	<p>
		Вы можете перестать играть в любой момент. Чтобы удалить аккаунт и связанные с ним данные, напишите на
		<a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a> с такого контакта, который поможет нам
		подтвердить, что аккаунт ваш. В <a href="/global-assault/privacy">Политике конфиденциальности</a> описано, что
		происходит с данными после этого.
	</p>
</section>

<section>
	<h2>11. Изменения этих условий</h2>
	<p>
		Мы можем обновлять эти условия. Действующая версия всегда находится на этой странице, с датой вверху. Если
		изменение важное, мы сообщим о нём в игре или в Discord до того, как оно вступит в силу. Если вы продолжаете
		играть после этого, значит, вы принимаете новую версию.
	</p>
</section>

