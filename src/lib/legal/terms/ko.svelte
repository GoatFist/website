<section>
	<h2>1. 운영자</h2>
	<p>
		Global Assault는 브라질의 개인이 운영하는 인디 스튜디오인 GOATFIST Interactive가 만듭니다. 문의는
		<a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a>으로 보내 주십시오.
	</p>
</section>

<section>
	<h2>2. 최소 연령</h2>
	<p>
		게임을 플레이하려면 만 18세 이상이어야 합니다. 이 게임에는 총기를 사용한 전투와 다른 플레이어와의 공개 채팅이 있으므로
		미성년자를 대상으로 하지 않습니다.
	</p>
	<p>
		계정이 만 18세 미만인 사람의 것으로 확인되면, 해당 계정을 해지하고 그 데이터를 삭제합니다.
	</p>
</section>

<section>
	<h2>3. 클로즈드 베타</h2>
	<p>
		Global Assault는 아직 개발 중입니다. 베타 기간에는 게임에 오류가 있거나, 점검으로 서비스가 중단되거나, 버전마다 내용이
		크게 바뀔 수 있습니다.
	</p>
	<p>
		베타가 끝날 때 또는 문제로 인해 필요한 경우 계정, 아이템, 진행 상황을 초기화할 수 있습니다. 가능한 경우에는 항상
		Discord에서 미리 알립니다.
	</p>
</section>

<section>
	<h2>4. 계정</h2>
	<p>
		게스트로 플레이하거나 아이디와 비밀번호로 계정을 만들 수 있습니다. 계정은 본인만 사용해야 합니다. 계정을 빌려주거나
		판매하지 말고, 다른 사람의 계정을 사용하지 마십시오. 비밀번호를 안전하게 관리하십시오. 계정에서 일어나는 모든 일은 이용자
		본인의 책임입니다.
	</p>
	<p>
		게스트 계정은 기기에 묶여 있습니다. 게임을 삭제하거나 휴대폰을 바꾸면 이 계정을 잃을 수 있습니다.
	</p>
</section>

<section>
	<h2>5. 행동 규칙</h2>
	<p>저희는 공정한 매치와 모두가 즐겁게 플레이하고 싶어 하는 환경을 원합니다. 따라서 다음 행위는 허용되지 않습니다.</p>
	<ul>
		<li>핵, 서드파티 프로그램, 매크로 등 게임 밖에서 이득을 주는 모든 수단을 사용하는 행위;</li>
		<li>버그를 신고하지 않고 고의로 악용하는 행위;</li>
		<li>채팅이나 이름으로 다른 플레이어를 모욕, 위협 또는 괴롭히는 행위;</li>
		<li>혐오 표현, 성적인 콘텐츠, 사기 또는 타인의 개인정보를 게시하는 행위;</li>
		<li>게임 운영팀을 사칭하는 행위;</li>
		<li>계정이나 아이템을 돈을 받고 사고팔거나 교환하는 행위;</li>
		<li>저희 서버를 공격하거나, 과부하를 일으키거나, 침입을 시도하는 행위.</li>
	</ul>
</section>

<section>
	<h2>6. 제재</h2>
	<p>
		규칙을 위반하면 위반의 정도에 따라 경고, 채팅 금지, 일정 기간 계정 정지 또는 영구 정지 조치를 할 수 있습니다. 부정행위의
		경우 바로 영구 정지될 수 있습니다.
	</p>
	<p>
		잘못된 조치라고 생각되면 계정 이름과 무슨 일이 있었는지를 적어
		<a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a>으로 보내 주십시오. 검토한 후 답변드리겠습니다.
	</p>
</section>

<section>
	<h2>7. 게임 아이템과 게임 머니</h2>
	<p>
		게임 머니, 무기, 외형 아이템 및 그 밖의 게임 아이템은 게임 안에서만 존재합니다. 이들은 금전적 가치가 없고, 현금으로 교환할
		수 없으며, 이용자의 소유물이 아닙니다. 이용자는 계정이 활성 상태인 동안 이를 사용할 권리를 받습니다.
	</p>
	<p>
		베타 기간에는 실제 돈으로 하는 구매가 없습니다. 이 점이 바뀌면 그보다 먼저 약관을 수정합니다.
	</p>
</section>

<section>
	<h2>8. 게임과 이용자의 콘텐츠</h2>
	<p>
		게임, 코드, 아트, 상표는 지식재산권으로 보호됩니다. 이용자는 게임을 플레이할 수 있는 개인적이고 무료이며 양도할 수 없는
		라이선스를 받습니다. 게임을 복제, 수정, 재판매 또는 배포하거나, 게임의 사설 서버나 별도 버전을 만드는 것은 허용되지
		않습니다.
	</p>
	<p>
		이용자가 채팅에 쓴 내용과 이용자가 정한 이름은 계속 이용자의 것이지만, 이용자는 저희가 이를 게임에 표시하고, 이 규칙을
		위반하는 경우 삭제하는 것을 허락합니다.
	</p>
</section>

<section>
	<h2>9. 서비스 제공과 책임</h2>
	<p>
		저희는 게임이 잘 작동하도록 최선을 다하지만, 게임이 항상 이용 가능하거나, 오류가 없거나, 모든 기기에서 작동한다고 보장하지
		않습니다. 저희는 언제든지 게임 또는 그 일부를 변경, 중단 또는 종료할 수 있습니다.
	</p>
	<p>
		법이 허용하는 범위에서, 저희는 기술적 장애로 인한 진행 상황이나 아이템의 손실과 같은 간접 손해에 대해 책임지지 않습니다.
		이 약관의 어떤 내용도 브라질 소비자보호법(Código de Defesa do Consumidor)이 이용자에게 보장하는 권리를 제한하지
		않습니다.
	</p>
</section>

