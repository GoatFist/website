<section>
	<p>
		Estos términos explican las reglas para jugar Global Assault. Al crear una cuenta o entrar al juego, aceptas
		estos términos. Si no estás de acuerdo, no juegues.
	</p>
	<p>
		El tratamiento de tus datos está en la <a href="/global-assault/privacy">Política de privacidad</a>, que forma parte
		de estos términos.
	</p>
</section>

<section>
	<h2>1. Quiénes somos</h2>
	<p>
		Global Assault lo hace GOATFIST Interactive, un estudio independiente a cargo de una persona física en
		Brasil. Para hablar con nosotros, escribe a <a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a>.
	</p>
</section>

<section>
	<h2>2. Edad mínima</h2>
	<p>
		Necesitas tener 18 años o más para jugar. El juego tiene combate con armas y chat abierto con otros jugadores, y
		por eso no es para menores de edad.
	</p>
	<p>
		Si descubrimos que una cuenta pertenece a alguien con menos de 18 años, la cerraremos y borraremos sus datos.
	</p>
</section>

<section>
	<h2>3. La beta cerrada</h2>
	<p>
		Global Assault todavía está en desarrollo. Durante la beta, el juego puede tener errores, quedar fuera de servicio por
		mantenimiento o cambiar bastante de una versión a otra.
	</p>
	<p>
		Podemos reiniciar cuentas, objetos y progreso al final de la beta o cuando un problema lo exija. Siempre que se pueda,
		avisaremos antes en Discord.
	</p>
</section>

<section>
	<h2>4. Tu cuenta</h2>
	<p>
		Puedes jugar como invitado o crear una cuenta con usuario y contraseña. La cuenta es personal: no la prestes, no la
		vendas y no uses la de otra persona. Cuida tu contraseña. Todo lo que pase en tu cuenta es tu responsabilidad.
	</p>
	<p>
		Una cuenta de invitado queda atada al dispositivo. Si desinstalas el juego o cambias de celular, puedes perder esa
		cuenta.
	</p>
</section>

<section>
	<h2>5. Reglas de conducta</h2>
	<p>Queremos partidas justas y un ambiente en el que todos quieran jugar. Por eso, no está permitido:</p>
	<ul>
		<li>usar trampas, programas de terceros, macros o cualquier cosa que dé ventaja fuera del juego;</li>
		<li>aprovechar fallos a propósito en lugar de reportarlos;</li>
		<li>insultar, amenazar o acosar a otros jugadores, en el chat o en el nombre;</li>
		<li>publicar discursos de odio, contenido sexual, estafas o datos personales de alguien;</li>
		<li>hacerse pasar por el equipo del juego;</li>
		<li>comprar, vender o intercambiar cuentas y objetos por dinero;</li>
		<li>atacar, sobrecargar o intentar invadir nuestros servidores.</li>
	</ul>
</section>

<section>
	<h2>6. Sanciones</h2>
	<p>
		Si alguien rompe las reglas, podemos darle una advertencia, silenciarle el chat, suspender la cuenta por un tiempo o
		expulsarla de forma definitiva, según la gravedad. En casos de trampa, la expulsión puede ser directa.
	</p>
	<p>
		Si crees que hubo un error, escribe a <a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a> indicando
		el nombre de la cuenta y lo que pasó. Lo revisaremos y te responderemos.
	</p>
</section>

<section>
	<h2>7. Objetos y monedas del juego</h2>
	<p>
		Las monedas, las armas, los aspectos y los demás objetos del juego existen solo dentro de él. No tienen valor en
		dinero, no se pueden cambiar por dinero y no son de tu propiedad: recibes el derecho de usarlos mientras tu cuenta
		esté activa.
	</p>
	<p>
		En la beta no hay compras con dinero real. Si eso cambia, los términos se actualizarán antes.
	</p>
</section>

<section>
	<h2>8. El juego y tu contenido</h2>
	<p>
		El juego, el código, el arte y las marcas están protegidos por derechos de propiedad intelectual. Recibes una
		licencia personal, gratuita e intransferible para jugar. No está permitido copiar, modificar, revender ni distribuir
		el juego, ni crear servidores o versiones paralelas de él.
	</p>
	<p>
		Lo que escribes en el chat y el nombre que eliges siguen siendo tuyos, pero nos autorizas a mostrarlos en el juego y
		a quitarlos si rompen estas reglas.
	</p>
</section>

<section>
	<h2>9. Disponibilidad y responsabilidad</h2>
	<p>
		Hacemos lo posible para que el juego funcione bien, pero no garantizamos que vaya a estar siempre en línea, sin errores
		o disponible en todos los dispositivos. Podemos cambiar, pausar o cerrar el juego, o partes de él, en cualquier momento.
	</p>
	<p>
		En la medida en que la ley lo permita, no respondemos por pérdidas indirectas, como progreso u objetos perdidos por
		fallos técnicos. Nada en estos términos te quita los derechos que te garantiza el Código de Defensa del Consumidor de
		Brasil (Código de Defesa do Consumidor).
	</p>
</section>

<section>
	<h2>10. Cómo cerrar la cuenta</h2>
	<p>
		Puedes dejar de jugar cuando quieras. Para borrar tu cuenta y los datos ligados a ella, escribe a
		<a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a> desde un contacto que nos ayude a confirmar
		que la cuenta es tuya. La <a href="/global-assault/privacy">Política de privacidad</a> explica qué pasa con los
		datos después de eso.
	</p>
</section>

<section>
	<h2>11. Cambios en estos términos</h2>
	<p>
		Podemos actualizar estos términos. La versión vigente siempre está en esta página, con la fecha arriba. Cuando el
		cambio sea importante, avisaremos en el juego o en Discord antes de que entre en vigor. Seguir jugando después de eso
		significa que aceptas la nueva versión.
	</p>
</section>

<section>
	<h2>12. Ley aplicable</h2>
	<p>
		Estos términos se rigen por las leyes de Brasil. Cualquier disputa puede llevarse a los tribunales de la ciudad donde
		vives.
	</p>
</section>
