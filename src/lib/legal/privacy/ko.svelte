	<ul>
		<li>게임과 데이터베이스가 실행되는 서버를 호스팅하는 회사;</li>
		<li>저희 API와의 연결을 보호하고 전달하는 Cloudflare.</li>
	</ul>
	<p>
		이용자가 Discord를 연동한 경우, 누군가 /profile로 이용자의 프로필을 요청하면 저희 Discord 서버의 봇이 이용자의 닉네임,
		레벨, 매치 통계, 클랜을 보여 줄 수 있습니다. 봇은 이 데이터를 읽기만 하며 절대 변경하지 않습니다.
	</p>
	<p>
		Google Play는 앱을 배포하고, Discord는 저희 커뮤니티를 호스팅합니다. 각 회사는 자체 개인정보 처리방침에 따라 이용자의
		데이터를 처리합니다. 또한 법률이나 법원의 명령이 요구하는 경우 당국에 데이터를 제공할 수 있습니다.
	</p>
</section>

