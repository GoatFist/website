<section>
	<h2>2. 보관하는 정보</h2>
	<p><strong>계정.</strong> 게임에 로그인하는 방식에 따라 다릅니다.</p>
	<ul>
		<li>
			아이디와 비밀번호로 로그인하는 경우: 아이디와 해시로 보호된 비밀번호를 보관하며, 비밀번호 원문은 절대 보관하지
			않습니다. 계정이 만들어진 시점과 마지막으로 로그인한 시점도 보관합니다.
		</li>
		<li>
			게스트로 로그인하는 경우: 게임은 Android 식별자와 앱 식별자를 결합하고 그 결과를 해시로 처리하여 기기용 코드를
			만듭니다. 이 코드는 휴대폰에 보호된 상태로 저장됩니다. 기기 식별자 자체는 저희에게 절대 전송되지 않습니다.
		</li>
		<li>
			Discord로 로그인하거나 나중에 설정 › 계정에서 연동하는 경우: Discord 계정을 식별하는 번호만 보관합니다. 이용자의
			이메일, 비밀번호, Discord 서버 목록은 보관하지 않습니다.
		</li>
	</ul>
	<p><strong>게임 내 활동.</strong></p>
	<ul>
		<li>닉네임, 경험치, 게임 머니, 아이템과 장비;</li>
		<li>통계와 매치 기록: 모드, 맵, 팀, 킬, 데스, 점수;</li>
		<li>친구 목록과 친구 요청, 클랜, 받은 좋아요;</li>
		<li>매치 리플레이(14일간 보관);</li>
		<li>계정에 적용된 제재와 그 사유;</li>
		<li>이용자가 이 약관과 이 방침에 동의한 시점과 동의한 버전.</li>
	</ul>
	<p><strong>부정행위 방지.</strong> 공정한 매치를 위해 게임은 앱이 정품인지, 부정행위 도구 없이 실행되고 있는지 확인합니다.
		이를 위해 다음 정보를 사용합니다.</p>
	<ul>
		<li>
			<strong>앱 무결성:</strong> 앱의 버전과 서명, 그리고 게임 파일이 변경되지 않았는지에 대한 확인 결과.
		</li>
		<li>
			<strong>게임 프로세스의 기술 정보:</strong> 게임에 작용하는 부정행위 도구나 디버깅 도구의 흔적.
		</li>
		<li>
			<strong>기기 환경:</strong> 에뮬레이터, 루팅, 앱 복제 도구의 흔적. 공정한 매치를 구성하는 데 사용됩니다(에뮬레이터로
			플레이하는 이용자는 다른 에뮬레이터 이용자와 함께 플레이합니다).
		</li>
		<li>
			<strong>매치 통계와 이벤트:</strong> 서버가 기록한 것으로, 불가능한 행동이어서 거부된 동작(벽을 관통한 사격, 불가능한
			움직임 등)이 여기에 해당합니다.
		</li>
	</ul>
