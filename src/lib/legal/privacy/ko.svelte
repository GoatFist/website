<section>
	<h2>4. 연결 정보</h2>
	<p>
		게임이 작동하려면 서버가 이용자 연결의 IP 주소를 알아야 합니다. IP 주소는 플레이하는 동안, 그리고 비밀번호를 추측하려는
		시도를 막는 데 사용되지만 계정에 저장되지는 않습니다. 오류를 찾는 데 쓰이는 서버의 기술 로그는 최대 14일 이내에 자동으로
		삭제됩니다.
	</p>
</section>

