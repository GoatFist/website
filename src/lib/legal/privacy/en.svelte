<section>
	<p>
		This page explains what data Global Assault uses, what it is for and what you can ask us to do. The idea is
		simple: we keep only what the game needs to work.
	</p>
</section>

<section>
	<h2>1. Who looks after your data</h2>
	<p>
		Global Assault is made by GOATFIST Interactive, an independent studio run by an individual in Brazil. That
		person is responsible for your data, what Brazil's General Data Protection Law (LGPD) calls the
		controller.
	</p>
	<p>
		For anything about privacy, write to
		<a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a>.
	</p>
</section>

<section>
	<h2>2. What we keep</h2>
	<p><strong>Your account.</strong> It depends on how you sign in to the game:</p>
	<ul>
		<li>
			With a username and password: we keep the username and a hash of the password, never the password itself. We
			also keep when the account was created and when you last signed in.
		</li>
		<li>
			As a guest: the game creates a code for your device by combining the Android identifier with the app's
			identifier and hashing the result. This code is stored securely on the phone. The device identifier itself is
			never sent to us.
		</li>
		<li>
			With Discord (to sign in, or linked later in Settings › Account): we keep only the number that identifies your
			Discord account. We do not keep your e-mail, your password or your Discord servers.
		</li>
	</ul>
	<p><strong>What you do in the game.</strong></p>
	<ul>
		<li>nickname, experience, in-game currency, items and equipment;</li>
		<li>stats and match history: mode, map, team, kills, deaths and points;</li>
		<li>friends list and friend requests, clan and likes received;</li>
		<li>match replays, kept for 14 days;</li>
		<li>penalties applied to the account, with the reason;</li>
		<li>when you accepted these terms and this policy, and which version.</li>
	</ul>
	<p><strong>Cheat protection.</strong> To keep matches fair, the game checks that the app is the original one and
		that it is running without cheating tools. For this we use:</p>
	<ul>
		<li>
			<strong>App integrity:</strong> the app's version and signature, and a check that the game's files have not
			been changed.
		</li>
		<li>
			<strong>Technical information about the game process:</strong> signs of cheating or debugging tools acting
			on the game.
		</li>
		<li>
			<strong>Device environment:</strong> signs of an emulator, root or an app cloner, used to make fair matches
			(players on an emulator play with other emulator players).
		</li>
		<li>
			<strong>Match stats and events</strong> recorded by the server, such as actions refused because they are
			impossible (a shot through a wall, an impossible movement).
		</li>
	</ul>
	<p>These signals are tied to your account, do not identify you outside the game, count for less over time and are deleted
		within 180 days. The protection looks only inside the game process: it does not read your list of installed apps, your files,
		your contacts or your location.</p>
	<p><strong>Closed beta.</strong> If you ask for access with the <code>/beta</code> command on our Discord, we keep your Discord
		account number, your username there and the access code generated, so we can unlock the beta on your account.</p>
	<p>
		We do not ask for your e-mail, real name, phone number or location, or for access to your contacts, photos or files.
	</p>
</section>

<section>
	<h2>3. What we do not keep</h2>
	<ul>
		<li>
			Chat goes through the server only to reach the other players. Messages are not stored.
		</li>
		<li>
			The game has no ads and no analytics or tracking tools, and it does not use the device's advertising
			ID.
		</li>
		<li>The only permission the app asks for on Android is internet access.</li>
	</ul>
</section>

<section>
	<h2>4. Connection data</h2>
	<p>
		For the game to work, the server needs to know your connection's IP address. It is used while you play and to
		block people who try to guess passwords, but it is not saved to the account. The servers' technical logs, used to
		find bugs, are deleted automatically within 14 days.
	</p>
</section>

<section>
	<h2>5. What we use it for</h2>
	<ul>
		<li>creating and keeping your account and your sign-in;</li>
		<li>showing your profile on our Discord, if you link your account;</li>
		<li>making matches, progress, the shop and friends work;</li>
		<li>fighting cheating and abuse and enforcing the <a href="/global-assault/terms">Terms of Use</a>;</li>
		<li>finding and fixing bugs;</li>
		<li>replying when you contact us.</li>
	</ul>
	<p>
		Under the LGPD, we use this data because it is needed to provide the game you asked for, to protect the game and
		the other players, which is a legitimate interest of ours, and to comply with the law when it requires it.
	</p>
</section>

<section>
	<h2>6. Who the data is shared with</h2>
	<p>We do not sell or rent your data. It only goes through those who help us keep the game running:</p>
	<ul>
		<li>the company that hosts the server where the game and the database run;</li>
		<li>Cloudflare, which protects and delivers the connection to our API.</li>
	</ul>
	<p>
		If you link Discord, the bot on our Discord server may show your nickname, level, match stats and clan when
		someone asks for your profile with /profile. It only reads this data and never changes it.
	</p>
	<p>
		Google Play distributes the app and Discord hosts our community. Each of them handles your data under its own
		privacy policy. We may also hand data over to authorities when a law or a court order
		requires it.
	</p>
</section>

<section>
	<h2>7. Where the data is kept</h2>
	<p>
		The servers and Cloudflare may process data outside Brazil. When that happens, we follow the LGPD's rules for
		international transfers.
	</p>
</section>

<section>
	<h2>8. How long</h2>
	<ul>
		<li>Account and game data are kept for as long as the account exists.</li>
		<li>Sign-ins expire after 30 days without use.</li>
		<li>Replays and technical logs are deleted within 14 days.</li>
		<li>Cheat protection signals are deleted within 180 days.</li>
		<li>
			When you delete your account in the game, the data is deleted right away; in other players' matches, your
			place shows as "Removed player". A request by e-mail is handled within 30 days. The record of a ban may be
			kept longer, only to stop the same person from cheating again.
		</li>
	</ul>
</section>

<section>
	<h2>9. Your rights</h2>
	<p>Under the LGPD (and, if you are in the European Union or the United Kingdom, under the GDPR), you can:</p>
	<ul>
		<li>confirm whether we have data about you and see what it is;</li>
		<li>correct anything that is wrong;</li>
		<li>delete your account and your data;</li>
		<li>get a copy of your data;</li>
		<li>find out who it has been shared with.</li>
	</ul>
	<p>
		In the game itself, under Settings › Account › Privacy and data, you can download a copy of everything we keep and
		delete your account right away. For anything else, just write to <a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a> with your nickname and, if you
		have one, your username. We may ask for some more information to make sure the account is yours.
		We reply within 15 days. If you are not satisfied, you can also complain to Brazil's National Data
		Protection Authority (ANPD) or, outside Brazil, to the data protection authority in your country.
	</p>
</section>

<section>
	<h2>10. Security</h2>
	<p>
		Passwords and sign-in tokens are stored only as hashes, the connection to our API is encrypted and access
		to the servers is limited to the team. No system is one hundred percent secure, but if something serious happens
		to your data, we will notify you and the ANPD as the law requires.
	</p>
</section>

<section>
	<h2>11. Minors</h2>
	<p>
		Global Assault is for people aged 18 and over. We do not knowingly collect data from minors. If we find an
		account belonging to someone under 18, it will be closed and its data deleted. If you are the parent or guardian
		of a minor who created an account, write to us.
	</p>
</section>

<section>
	<h2>12. Changes to this policy</h2>
	<p>
		If the game starts using data in a different way, for example with Google sign-in or purchases, we update this
		page first. The date at the top shows the version in effect, and important changes are announced in the game or on
		Discord.
	</p>
</section>
