<section>
	<p>
		Esta página explica qué datos usa Global Assault, para qué sirven y qué nos puedes pedir. La idea es
		simple: guardamos solo lo que el juego necesita para funcionar.
	</p>
</section>

<section>
	<h2>1. Quién se encarga de tus datos</h2>
	<p>
		Global Assault lo hace GOATFIST Interactive, un estudio independiente a cargo de una persona física en
		Brasil. Esa persona es la responsable de tus datos, lo que la LGPD (Ley General de Protección de Datos de
		Brasil) llama controlador.
	</p>
	<p>
		Para cualquier tema de privacidad, escribe a
		<a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a>.
	</p>
</section>

<section>
	<h2>2. Qué guardamos</h2>
	<p><strong>Tu cuenta.</strong> Depende de cómo entres al juego:</p>
	<ul>
		<li>
			Con usuario y contraseña: guardamos el nombre de usuario y la contraseña protegida con hash, nunca la contraseña
			en sí. También guardamos cuándo se creó la cuenta y cuándo entraste por última vez.
		</li>
		<li>
			Como invitado: el juego crea un código para tu dispositivo, combinando el identificador de Android con el de la
			app y pasando el resultado por un hash. Ese código queda guardado de forma protegida en el celular. El
			identificador del dispositivo en sí nunca se nos envía.
		</li>
		<li>
			Con Discord (para entrar o vinculado después, en Ajustes › Cuenta): guardamos solo el número que identifica tu
			cuenta de Discord. No guardamos tu e-mail, tu contraseña ni tus servidores de Discord.
		</li>
	</ul>
	<p><strong>Lo que haces en el juego.</strong></p>
	<ul>
		<li>apodo, experiencia, monedas del juego, objetos y equipamiento;</li>
		<li>estadísticas e historial de partidas: modo, mapa, equipo, bajas, muertes y puntos;</li>
		<li>lista de amigos y solicitudes de amistad, clan y "me gusta" recibidos;</li>
		<li>repeticiones de las partidas, guardadas durante 14 días;</li>
		<li>sanciones aplicadas a la cuenta, con el motivo;</li>
		<li>cuándo aceptaste estos términos y esta política, y qué versión.</li>
	</ul>
	<p><strong>Protección contra trampas.</strong> Para mantener las partidas justas, el juego verifica que la app sea la original
		y que funcione sin herramientas de trampa. Para eso usamos:</p>
	<ul>
		<li>
			<strong>Integridad de la aplicación:</strong> la versión y la firma de la app y la verificación de que los archivos
			del juego no fueron modificados.
		</li>
		<li>
			<strong>Información técnica del proceso del juego:</strong> señales de herramientas de trampa o de depuración que
			actúan sobre el juego.
		</li>
		<li>
			<strong>Entorno del dispositivo:</strong> señales de emulador, root o app clonadora, usadas para armar partidas justas
			(quien juega en emulador juega con otros jugadores de emulador).
		</li>
		<li>
			<strong>Estadísticas y eventos de la partida</strong> registrados por el servidor, como acciones rechazadas por ser
			imposibles (un disparo a través de la pared, un movimiento imposible).
		</li>
	</ul>
	<p>Estas señales quedan ligadas a tu cuenta, no te identifican fuera del juego, pierden peso con el tiempo y se borran en
		un plazo de 180 días. La protección mira solamente dentro del proceso del juego: no lee la lista de apps instaladas, tus
		archivos, tus contactos ni tu ubicación.</p>
	<p><strong>Beta cerrada.</strong> Si pides acceso con el comando <code>/beta</code> en nuestro Discord, guardamos el número
		de tu cuenta de Discord, tu nombre de usuario allí y el código de acceso generado, para habilitar la beta en tu cuenta.</p>
	<p>
		No pedimos e-mail, nombre real, teléfono, ubicación ni acceso a tus contactos, fotos o archivos.
	</p>
</section>

<section>
	<h2>3. Qué no guardamos</h2>
	<ul>
		<li>
			El chat pasa por el servidor solo para llegar a los otros jugadores. Los mensajes no se graban.
		</li>
		<li>
			El juego no tiene anuncios ni herramientas de análisis o de rastreo, y no usa el ID de publicidad del
			dispositivo.
		</li>
		<li>El único permiso que pide la app en Android es el acceso a internet.</li>
	</ul>
</section>

<section>
	<h2>4. Datos de la conexión</h2>
	<p>
		Para que el juego funcione, el servidor necesita saber la dirección IP de tu conexión. Se usa mientras juegas y
		para bloquear a quien intenta adivinar contraseñas, pero no se guarda en la cuenta. Los registros técnicos de los
		servidores, que usamos para encontrar errores, se borran solos en un plazo de 14 días.
	</p>
</section>

<section>
	<h2>5. Para qué los usamos</h2>
	<ul>
		<li>crear y mantener tu cuenta y tu inicio de sesión;</li>
		<li>mostrar tu perfil en nuestro Discord, si vinculas la cuenta;</li>
		<li>hacer que funcionen las partidas, el progreso, la tienda y los amigos;</li>
		<li>combatir las trampas y el abuso y aplicar las reglas de los <a href="/global-assault/terms">Términos de uso</a>;</li>
		<li>encontrar y corregir errores;</li>
		<li>responderte cuando nos escribes.</li>
	</ul>
	<p>
		Según la LGPD, usamos estos datos porque son necesarios para ofrecerte el juego que pediste, para proteger el juego
		y a los demás jugadores, que es un interés legítimo nuestro, y para cumplir la ley cuando lo exija.
	</p>
</section>

<section>
	<h2>6. Con quién se comparten los datos</h2>
	<p>No vendemos ni alquilamos tus datos. Solo pasan por quienes nos ayudan a mantener el juego en funcionamiento:</p>
	<ul>
		<li>la empresa que aloja el servidor donde funcionan el juego y la base de datos;</li>
		<li>Cloudflare, que protege y entrega la conexión con nuestra API.</li>
	</ul>
	<p>
		Si vinculas Discord, el bot de nuestro servidor de Discord puede mostrar, cuando alguien pide tu perfil con
		/profile, tu apodo, nivel, estadísticas de partidas y clan. Solo lee esos datos, nunca los modifica.
	</p>
	<p>
		Google Play distribuye la app y Discord aloja nuestra comunidad. Cada uno trata tus datos según su propia
		política de privacidad. También podemos entregar datos a las autoridades cuando una ley o una orden judicial lo
		exija.
	</p>
</section>

<section>
	<h2>7. Dónde están los datos</h2>
	<p>
		Los servidores y Cloudflare pueden procesar datos fuera de Brasil. Cuando eso ocurre, seguimos las reglas de la
		LGPD para la transferencia internacional.
	</p>
</section>

<section>
	<h2>8. Por cuánto tiempo</h2>
	<ul>
		<li>Los datos de la cuenta y del juego se conservan mientras exista la cuenta.</li>
		<li>Las sesiones iniciadas vencen tras 30 días sin uso.</li>
		<li>Las repeticiones y los registros técnicos se borran en un plazo de 14 días.</li>
		<li>Las señales de la protección contra trampas se borran en un plazo de 180 días.</li>
		<li>
			Cuando eliminas la cuenta en el juego, los datos se borran en el acto; en las partidas de otros jugadores, tu
			lugar aparece como "Jugador eliminado". Una solicitud por e-mail se atiende en un plazo de 30 días. El registro de
			una expulsión puede conservarse por más tiempo, solo para impedir que la misma persona vuelva a hacer trampa.
		</li>
	</ul>
</section>

<section>
	<h2>9. Tus derechos</h2>
	<p>Según la LGPD (y, si estás en la Unión Europea o en el Reino Unido, según el RGPD, también conocido como GDPR), puedes:</p>
	<ul>
		<li>confirmar si tenemos datos tuyos y ver cuáles son;</li>
		<li>corregir lo que esté mal;</li>
		<li>borrar tu cuenta y tus datos;</li>
		<li>recibir una copia de tus datos;</li>
		<li>saber con quién se compartieron.</li>
	</ul>
	<p>
		En el propio juego, en Ajustes › Cuenta › Privacidad y datos, puedes descargar una copia de todo lo que guardamos y
		eliminar tu cuenta en el acto. Para lo demás, basta con escribir a <a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a> con tu apodo y, si
		lo tienes, tu nombre de usuario. Podemos pedirte algún dato más para confirmar que la cuenta es tuya.
		Respondemos en un plazo de 15 días. Si no quedas conforme, también puedes presentar un reclamo ante la Autoridad
		Nacional de Protección de Datos de Brasil (ANPD) o, fuera de Brasil, ante la autoridad de protección de datos de tu país.
	</p>
</section>

<section>
	<h2>10. Seguridad</h2>
	<p>
		Las contraseñas y los tokens de inicio de sesión se guardan solo como hash, la conexión con nuestra API está cifrada
		y el acceso a los servidores está restringido al equipo. Ningún sistema es cien por ciento seguro, pero, si algo grave
		les pasa a tus datos, te avisaremos a ti y a la ANPD como lo exige la ley.
	</p>
</section>

<section>
	<h2>11. Menores de edad</h2>
	<p>
		Global Assault es para mayores de 18 años. No recopilamos a propósito datos de menores. Si descubrimos una
		cuenta de alguien con menos de 18 años, la cerraremos y borraremos sus datos. Si eres responsable de un menor
		que creó una cuenta, escríbenos.
	</p>
</section>

<section>
	<h2>12. Cambios en esta política</h2>
	<p>
		Si el juego empieza a usar los datos de otra forma, por ejemplo con inicio de sesión con Google o compras,
		actualizaremos esta página antes. La fecha de arriba muestra la versión vigente, y los cambios importantes se
		avisan en el juego o en Discord.
	</p>
</section>
