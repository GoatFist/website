	<p>
		如有任何隐私方面的问题，请发送邮件至
		<a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a>。
	</p>
</section>

<section>
	<h2>2. 我们保存哪些数据</h2>
	<p><strong>你的账号。</strong>取决于你进入游戏的方式：</p>
	<ul>
		<li>
			使用用户名和密码：我们保存用户名和经过哈希处理的密码，从不保存密码本身。我们还会记录账号的创建时间和你最后一次登录的时间。
		</li>
		<li>
			以游客身份：游戏会为你的设备生成一个代码，方法是将 Android 设备标识符与应用标识符组合后进行哈希处理。该代码以受保护的方式保存在手机上。设备标识符本身从不会发送给我们。
		</li>
		<li>
			使用 Discord（用于登录，或之后在“设置 › 账号”中绑定）：我们只保存识别你 Discord 账号的那串数字编号。我们不保存你的电子邮件地址、密码，也不保存你所在的 Discord 服务器。
		</li>
	</ul>
	<p><strong>你在游戏中的活动。</strong></p>
	<ul>
		<li>昵称、经验值、游戏币、物品和装备；</li>
		<li>统计数据和对局记录：模式、地图、队伍、击杀、死亡和得分；</li>
		<li>好友列表和好友请求、战队以及收到的点赞；</li>
		<li>对局回放，保存 14 天；</li>
		<li>账号受到的处罚及其原因；</li>
		<li>你接受本条款和本政策的时间及对应版本。</li>
	</ul>
	<p><strong>反作弊保护。</strong>为了保证对局公平，游戏会检查应用是否为正版，以及运行时是否有作弊工具。为此我们使用：</p>
	<ul>
		<li>
			<strong>应用完整性：</strong>应用的版本和签名，以及对游戏文件未被篡改的校验。
		</li>
		<li>
			<strong>游戏进程的技术信息：</strong>作弊工具或调试工具作用于游戏的迹象。
		</li>
		<li>
			<strong>设备环境：</strong>模拟器、root 或应用分身的迹象，用于安排公平的匹配（在模拟器上玩的玩家会与其他模拟器玩家匹配）。
		</li>
		<li>
			由服务器记录的<strong>对局统计数据和事件</strong>，例如因不可能发生而被拒绝的操作（穿墙射击、不可能的移动）。
		</li>
	</ul>
	<p>这些迹象与你的账号关联，不会在游戏之外识别你的身份，其权重会随时间降低，并在 180 天内删除。反作弊保护只检查游戏进程内部：不会读取已安装应用列表、你的文件、联系人或位置。</p>
	<p><strong>封闭测试。</strong>如果你在我们的 Discord 中使用 <code>/beta</code> 命令申请资格，我们会保存你的 Discord 账号编号、你在 Discord 上的用户名以及生成的访问码，以便为你的账号开通测试资格。</p>
	<p>
		我们不会要求你提供电子邮件地址、真实姓名、电话号码或位置，也不会请求访问你的联系人、照片或文件。
	</p>
</section>

<section>
	<h2>3. 我们不保存哪些数据</h2>
	<ul>
		<li>
			聊天消息经过服务器只是为了发送给其他玩家。消息不会被记录。
		</li>
		<li>
			游戏没有广告，没有分析或追踪工具，也不使用设备的广告 ID。
		</li>
		<li>应用在 Android 上唯一申请的权限是网络访问。</li>
	</ul>
</section>

<section>
	<h2>4. 连接数据</h2>
	<p>
		为了让游戏正常运行，服务器需要知道你所用连接的 IP 地址。该地址在你游戏期间使用，也用于拦截试图猜测密码的人，但不会保存在账号中。服务器的技术日志用于排查错误，会在 14 天内自动删除。
	</p>
</section>

<section>
	<h2>5. 我们如何使用这些数据</h2>
	<ul>
		<li>创建和维护你的账号及登录；</li>
		<li>如果你绑定了账号，在我们的 Discord 中展示你的资料；</li>
		<li>让对局、进度、商店和好友功能正常运行；</li>
		<li>打击作弊和滥用行为，执行<a href="/global-assault/terms">使用条款</a>中的规则；</li>
		<li>发现并修复错误；</li>
		<li>在你联系我们时给予答复。</li>
	</ul>
	<p>
		根据 LGPD，我们使用这些数据的依据是：为提供你所请求的游戏所必需；为保护游戏和其他玩家，这属于我们的正当利益；以及在法律要求时履行法定义务。
	</p>
</section>

<section>
	<h2>6. 我们与谁共享数据</h2>
	<p>我们不出售也不出租你的数据。数据只会经过帮助我们维持游戏运行的服务方：</p>
	<ul>
		<li>托管游戏和数据库所在服务器的公司；</li>
		<li>Cloudflare，负责保护并传输与我们 API 之间的连接。</li>
	</ul>
	<p>
		如果你绑定了 Discord，当有人用 /profile 查询你的资料时，我们 Discord 服务器中的机器人可以展示你的昵称、等级、对局统计数据和战队。它只读取这些数据，从不修改。
	</p>
	<p>
		Google Play 负责分发应用，Discord 托管我们的社区。它们各自依照自己的隐私政策处理你的数据。在法律或法院命令要求时，我们也可能向有关机关提供数据。
	</p>
</section>

<section>
	<h2>7. 数据存放在哪里</h2>
	<p>
		服务器和 Cloudflare 可能在巴西境外处理数据。在这种情况下，我们遵守 LGPD 关于国际传输的规定。
	</p>
</section>

<section>
	<h2>8. 保存多久</h2>
	<ul>
		<li>账号和游戏数据在账号存续期间一直保存。</li>
		<li>登录状态在 30 天未使用后失效。</li>
		<li>回放和技术日志在 14 天内删除。</li>
		<li>反作弊保护记录的迹象在 180 天内删除。</li>
		<li>
			当你在游戏中删除账号时，数据会立即删除；在其他玩家的对局记录中，你的位置将显示为“已移除的玩家”。通过电子邮件提出的请求会在 30 天内处理。封禁记录可能会保存更长时间，仅用于防止同一个人再次作弊。
		</li>
	</ul>
</section>

<section>
	<h2>9. 你的权利</h2>
	<p>根据 LGPD（如果你身处欧盟或英国，还包括 GDPR），你可以：</p>
	<ul>
		<li>确认我们是否持有你的数据，并查看是哪些数据；</li>
		<li>更正有误的内容；</li>
		<li>删除你的账号和数据；</li>
		<li>获取一份你的数据副本；</li>
		<li>了解你的数据被共享给了谁。</li>
	</ul>
	<p>
		在游戏内的“设置 › 账号 › 隐私与数据”中，你可以下载我们保存的全部数据的副本，也可以立即删除账号。其他事项，只需发送邮件至 <a href="mailto:privacy@goatfist.com">privacy@goatfist.com</a>，写明你的昵称以及用户名（如有）。我们可能会要求你提供一些额外信息，以确认账号属于你。我们会在 15 天内答复。如果你对处理结果不满意，也可以向巴西国家数据保护局（ANPD）投诉；如果你不在巴西，可以向你所在国家的数据保护机构投诉。
	</p>
</section>

<section>
	<h2>10. 安全</h2>
	<p>
		密码和登录令牌只以哈希形式保存，与我们 API 之间的连接经过加密，服务器的访问权限仅限团队成员。没有任何系统是百分之百安全的，但如果你的数据发生严重事件，我们会依法通知你和 ANPD。
	</p>
</section>

<section>
	<h2>11. 未成年人</h2>
	<p>
		Global Assault 仅面向 18 岁及以上的用户。我们不会有意收集未成年人的数据。如果发现账号属于未满 18 岁的人，我们会关闭该账号并删除其数据。如果你是某位已创建账号的未成年人的监护人，请与我们联系。
	</p>
</section>

<section>
	<h2>12. 本政策的变更</h2>
	<p>
		如果游戏开始以其他方式使用数据，例如加入 Google 登录或购买功能，我们会事先更新本页面。顶部的日期表示现行版本，重要变更会在游戏内或 Discord 上通知。
	</p>
</section>
