<section>
	<h2>2. Что мы храним</h2>
	<p><strong>Ваш аккаунт.</strong> Зависит от того, как вы входите в игру:</p>
	<ul>
		<li>
			С логином и паролем: мы храним имя пользователя и хеш пароля, но никогда сам пароль. Также мы храним, когда
			аккаунт был создан и когда вы входили в последний раз.
		</li>
		<li>
			Как гость: игра создаёт код для вашего устройства, объединяя идентификатор Android с идентификатором
			приложения и пропуская результат через хеш-функцию. Этот код хранится на телефоне в защищённом виде. Сам
			идентификатор устройства нам никогда не отправляется.
		</li>
		<li>
			Через Discord (для входа или если вы привязали его позже, в разделе «Настройки › Аккаунт»): мы храним только
			номер, который идентифицирует ваш аккаунт Discord. Мы не храним ваш e-mail, пароль или ваши серверы Discord.
		</li>
	</ul>
	<p><strong>Что вы делаете в игре.</strong></p>
	<ul>
		<li>никнейм, опыт, игровая валюта, предметы и снаряжение;</li>
		<li>статистика и история матчей: режим, карта, команда, убийства, смерти и очки;</li>
		<li>список друзей и заявки в друзья, клан и полученные лайки;</li>
		<li>повторы матчей, которые хранятся 14 дней;</li>
		<li>наказания, применённые к аккаунту, с указанием причины;</li>
		<li>когда вы приняли эти условия и эту политику и в какой версии.</li>
	</ul>
	<p><strong>Защита от читов.</strong> Чтобы матчи оставались честными, игра проверяет, что приложение оригинальное и
		работает без читерских инструментов. Для этого мы используем:</p>
	<ul>
		<li>
			<strong>Целостность приложения:</strong> версию и подпись приложения и проверку того, что файлы игры не были
			изменены.
		</li>
		<li>
			<strong>Технические сведения о процессе игры:</strong> признаки того, что на игру воздействуют читерские или
			отладочные инструменты.
		</li>
		<li>
			<strong>Окружение устройства:</strong> признаки эмулятора, root-прав или приложения-клонировщика, которые
			используются для подбора честных матчей (игроки на эмуляторе играют с другими игроками на эмуляторе).
		</li>
		<li>
			<strong>Статистику и события матча</strong>, которые записывает сервер, например действия, отклонённые как
			невозможные (выстрел сквозь стену, невозможное перемещение).
		</li>
	</ul>
	<p>Эти сигналы привязаны к вашему аккаунту, не идентифицируют вас за пределами игры, со временем теряют вес и
		удаляются не позднее чем через 180 дней. Защита смотрит только внутрь процесса игры: она не читает список
		установленных приложений, ваши файлы, контакты или местоположение.</p>
	<p><strong>Закрытая бета.</strong> Если вы запросите доступ командой <code>/beta</code> в нашем Discord, мы сохраним
		номер вашего аккаунта Discord, ваше имя пользователя там и сгенерированный код доступа, чтобы открыть бету для
		вашего аккаунта.</p>
	<p>
		Мы не запрашиваем e-mail, настоящее имя, телефон, местоположение или доступ к вашим контактам, фотографиям или
		файлам.
	</p>
