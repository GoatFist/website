		<h2>2. Informações tratadas</h2>
		<p>O Jogo utiliza um backend próprio para oferecer recursos online. Os dados efetivamente recebidos e armazenados dependem da implementação do servidor e dos recursos usados pelo jogador. Conforme o funcionamento real do Jogo, isso poderá incluir:</p>
		<ul>
			<li><strong>Conta e autenticação:</strong> identificadores de conta ou jogador e informações necessárias para autenticar o usuário, caso sejam transmitidas ao backend. Se o login for feito por um provedor externo, esse provedor poderá tratar dados de acordo com sua própria política.</li>
			<li><strong>Perfil e progresso:</strong> nome de exibição, preferências, progresso, inventário virtual, estatísticas e resultados de partidas, somente na medida em que esses dados sejam enviados ou salvos pelo backend.</li>
			<li><strong>Dados técnicos e de conexão:</strong> informações técnicas recebidas durante a comunicação com o servidor, como endereço IP, horário e registros de solicitações, caso o servidor, a hospedagem ou a infraestrutura os registre.</li>
			<li><strong>Suporte:</strong> informações que você decidir enviar por e-mail ao entrar em contato com o Desenvolvedor.</li>
		</ul>
		<p>Esta lista apresenta categorias possíveis a serem confirmadas, não uma declaração de que todos esses dados são necessariamente coletados. O Desenvolvedor deve verificar os registros do servidor, os bancos de dados e os fluxos de autenticação para identificar exatamente quais informações são tratadas.</p>
	</section>
	<section>
		<h2>3. Finalidades do tratamento</h2>
		<p>Quando aplicável e necessário ao funcionamento do Jogo, as informações poderão ser usadas para:</p>
		<ul>
			<li>autenticar jogadores e manter a sessão de acesso;</li>
			<li>fornecer recursos online, sincronizar progresso e registrar resultados de partidas;</li>
			<li>manter a integridade do serviço e investigar erros, abusos ou atividades fraudulentas;</li>
			<li>proteger a segurança do backend e a estabilidade do Jogo;</li>
			<li>responder a solicitações enviadas ao suporte; e</li>
			<li>cumprir obrigações legais aplicáveis.</li>
		</ul>
		<p>Os dados não devem ser utilizados para finalidades incompatíveis com aquelas informadas ao jogador ou sem uma base legal adequada.</p>
